$coin = static function (string $slug, array $c): array {
    $fields = [
        'thb_symbol'             => $c['sym'],
        'thb_name_fa'            => $c['fa'],
        'thb_name_en'            => $c['en'],
        'thb_coingecko_id'       => $c['cg'],
        'thb_news_category_slug' => $slug . '-news',
        'thb_description'        => $c['desc'],
        'thb_founder'            => $c['founder'],
        'thb_consensus'          => $c['consensus'],
        'thb_tags'               => $c['tags'],
        'thb_website'            => $c['site'],
        'thb_explorer'           => $c['explorer'],
        'thb_unlocks'            => $c['unlocks'],
        'thb_tagline'            => $c['tagline'],
        'thb_seo_title'          => $c['seo'],
        'thb_meta_description'   => $c['meta'],
        'thb_timeline'           => implode("\n", $c['timeline']),
        'thb_price_events'       => implode("\n", $c['events']),
        'thb_learn'              => implode("\n", $c['learn']),
        'thb_audience'           => implode("\n", $c['audience']),
        'thb_faq'                => implode("\n", $c['faq']),
        'thb_enable_defi'        => isset($c['chain']) ? 1 : 0,
        'thb_enable_dex'         => isset($c['dex']) ? 1 : 0,
        'thb_enable_onchain'     => 0,
        'thb_enable_l2'          => 0,
    ];
    foreach (['wiki' => 'thb_wikipedia', 'dex' => 'thb_dex_token_address', 'chain' => 'thb_defillama_chain',
              'repo' => 'thb_github_repo', 'launch' => 'thb_launch_date', 'dexsym' => 'thb_dex_symbols'] as $k => $field) {
        if (isset($c[$k]) && $c[$k] !== '') {
            $fields[$field] = $c[$k];
        }
    }
    return ['post_title' => $c['fa'], 'fields' => $fields, 'verify' => $c['verify'] ?? [], 'batch' => 4];
};

